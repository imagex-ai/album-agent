def diff_dicts(d1, d2, path=""):
    diffs = []
    for k in d1:
        new_path = f"{path}.{k}" if path else k
        if k not in d2:
            diffs.append(f"Missing in target: {new_path}")
        elif isinstance(d1[k], dict):
            if not isinstance(d2[k], dict):
                diffs.append(f"Type mismatch: {new_path}")
            else:
                diffs.extend(diff_dicts(d1[k], d2[k], new_path))
    for k in d2:
        new_path = f"{path}.{k}" if path else k
        if k not in d1:
            diffs.append(f"Missing in source: {new_path}")
    return diffs

diffs = diff_dicts(pt_BR, en_US)
if diffs:
    print("DIFF ERRORS FOUND:")
    for d in diffs:
        print("  -", d)
    exit(1)
else:
    print("Verification passed! pt-BR and en-US are 100% mirrored.")

